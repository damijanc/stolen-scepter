"""Clean-room open art pack: functional spec, validation and local assembly.

The committed `packs/open/` tree holds ORIGINAL art only. This tool never
reads the original pixels to produce art; it works from the functional spec in
`tools/hd_assets.json` (paths, sizes, frame counts, alpha) and validates what
an artist supplies:

    python3 tools/open_pack.py checklist   # write packs/open/CHECKLIST.md
    python3 tools/open_pack.py verify      # coverage, sizes, alpha, provenance
    python3 tools/open_pack.py build       # assemble a runnable pack to run

`build` overlays `packs/open/art` onto the (gitignored) reference pack and
patches `render.scale`; the result is a local playtest pack, never committed.
`verify` also flags any file that is byte-identical to, or a near match for,
the original or an upscale of it, so a derivative cannot slip in.
"""
import argparse
import json
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from upscale import read_png  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "tools", "hd_assets.json")
PACK = os.path.join(ROOT, "packs", "open")
ART = os.path.join(PACK, "art")
PROVENANCE = os.path.join(PACK, "provenance.json")
CHECKLIST = os.path.join(PACK, "CHECKLIST.md")
REFERENCE = os.path.join(ROOT, "reference", "assets", "kings-bounty")
EXTRACTED = os.path.join(ROOT, "game-assets", "extracted")
GENERATED = os.path.join(ROOT, "game-assets", "generated")
BUILD_OUT = os.path.join(ROOT, "game-assets", "open-pack")

FRAME_RE = re.compile(r"^(.*)_(\d{2})\.png$")


def required_assets():
    with open(MANIFEST) as fh:
        manifest = json.load(fh)
    return [a for a in manifest["assets"] if a["engine_used"]]


def pack_file(rel):
    """Map a pack-relative art path (`art/tiles/x.png`) to the open-pack file."""
    sub = rel[len("art/"):] if rel.startswith("art/") else rel
    return os.path.join(ART, sub)


def group_of(path):
    """(group path, frame) for an animated slot, else (path, None)."""
    directory, name = os.path.split(path)
    m = FRAME_RE.match(name)
    if m:
        return f"{directory}/{m.group(1)}", int(m.group(2))
    return path, None


def cmd_checklist(_args):
    assets = required_assets()
    by_cat = {}
    for a in assets:
        cat = a["path"].split("/")[1]
        by_cat.setdefault(cat, []).append(a)

    lines = [
        "# Open art pack checklist",
        "",
        "Generated by `tools/open_pack.py checklist` from `tools/hd_assets.json`.",
        "Every line is one slot the engine can draw. Draw it, drop it at the",
        "listed path under `packs/open/art/`, then add a `provenance.json` entry.",
        "Native sizes are the base; multiply by the pack scale if you author HD.",
        "",
    ]
    total = 0
    for cat in sorted(by_cat):
        groups = {}
        for a in by_cat[cat]:
            g, frame = group_of(a["path"])
            groups.setdefault(g, {"frames": [], "alpha": a["alpha"],
                                  "native": a["native"], "role": a["role"]})
            groups[g]["frames"].append((frame, a["path"]))
        lines.append(f"## {cat} ({len(by_cat[cat])})")
        lines.append("")
        for g in sorted(groups):
            info = groups[g]
            frames = sorted(f for f, _ in info["frames"] if f is not None)
            n = len(info["frames"])
            size = f"{info['native']['w']}x{info['native']['h']}"
            if not frames:
                label = g
            elif len(frames) == 1:
                label = f"{g}_{frames[0]:02d}.png"
            else:
                label = f"{g}_{frames[0]:02d}.._{frames[-1]:02d}.png"
            present = sum(1 for _, p in info["frames"] if os.path.exists(pack_file(p)))
            tick = "x" if present == n else " "
            note = f"  ({present}/{n})" if 0 < present < n else ""
            lines.append(f"- [{tick}] `{label}` - {n} frame(s), {size}, {info['alpha']}, "
                         f"{info['role']}{note}")
            total += n
        lines.append("")
    lines.append(f"Total: {total} slots.")
    lines.append("")
    os.makedirs(PACK, exist_ok=True)
    with open(CHECKLIST, "w") as fh:
        fh.write("\n".join(lines))
    print(f"{os.path.relpath(CHECKLIST, ROOT)}: {total} slots")
    return 0


def _sig_from(w, h, rgba):
    cw, ch = 16, 12
    out = []
    for cy in range(ch):
        for cx in range(cw):
            x0, x1 = cx * w // cw, max(cx * w // cw + 1, (cx + 1) * w // cw)
            y0, y1 = cy * h // ch, max(cy * h // ch + 1, (cy + 1) * h // ch)
            acc = [0, 0, 0, 0]
            n = 0
            for y in range(y0, y1):
                row = y * w * 4
                for x in range(x0, x1):
                    o = row + x * 4
                    for c in range(4):
                        acc[c] += rgba[o + c]
                    n += 1
            out.append(tuple(v // n for v in acc))
    return out


def _sig(path):
    return _sig_from(*read_png(path))


def _dist(a, b):
    return sum(abs(p - q) for pa, pb in zip(a, b) for p, q in zip(pa, pb)) / (len(a) * 4)


def cmd_verify(args):
    assets = required_assets()
    with open(PROVENANCE) as fh:
        prov_doc = json.load(fh)
    prov = prov_doc.get("assets", {})
    pack_license = prov_doc.get("license")

    present = errors = warnings = 0
    for a in assets:
        rel = a["path"]
        src = pack_file(rel)
        want = (a["native"]["w"] * args.scale, a["native"]["h"] * args.scale)
        if not os.path.exists(src):
            if args.verbose:
                print(f"  missing  {rel}")
            continue
        present += 1
        w, h, rgba = read_png(src)
        if (w, h) != want:
            print(f"  SIZE     {rel}: {w}x{h}, want {want[0]}x{want[1]}", file=sys.stderr)
            errors += 1
            continue
        alphas = {rgba[i] for i in range(3, len(rgba), 4)}
        if a["alpha"] == "opaque" and alphas != {255}:
            print(f"  ALPHA    {rel}: tiles must be fully opaque", file=sys.stderr)
            errors += 1
        elif a["alpha"] == "color_key" and not alphas <= {0, 255}:
            print(f"  ALPHA    {rel}: colour-key art needs hard 0/255 alpha", file=sys.stderr)
            errors += 1
        entry = prov.get(rel)
        if entry is None:
            print(f"  PROVENANCE {rel}: no provenance.json entry", file=sys.stderr)
            errors += 1
        elif pack_license and entry.get("license") != pack_license:
            print(f"  LICENSE  {rel}: entry license {entry.get('license')!r} != "
                  f"pack license {pack_license!r}", file=sys.stderr)
            errors += 1

        sig = _sig_from(w, h, rgba)
        for label, base in (("reference", REFERENCE), ("extracted", EXTRACTED),
                            ("generated", GENERATED)):
            other = os.path.join(base, rel)
            if not os.path.exists(other):
                continue
            w2, h2, rgba2 = read_png(other)
            if (w2, h2) == (w, h) and rgba2 == rgba:
                print(f"  DERIVATIVE {rel}: pixel-identical to {label} art", file=sys.stderr)
                errors += 1
                break
            if (w2, h2) == (w, h):
                d = _dist(sig, _sig_from(w2, h2, rgba2))
                if d < args.similarity:
                    print(f"  SIMILAR  {rel}: score {d:.1f} vs {label} (threshold "
                          f"{args.similarity}); review for copying", file=sys.stderr)
                    warnings += 1
                    break

    print(f"verify: {present}/{len(assets)} present, {errors} errors, {warnings} warnings "
          f"(scale {args.scale})")
    return 1 if errors else 0


def cmd_build(args):
    if not os.path.isdir(REFERENCE):
        sys.exit(f"reference pack not found at {REFERENCE}")
    if os.path.isdir(BUILD_OUT) and not args.keep:
        shutil.rmtree(BUILD_OUT)
    shutil.copytree(REFERENCE, BUILD_OUT, dirs_exist_ok=True)

    overlaid = 0
    if os.path.isdir(ART):
        for root, _, files in os.walk(ART):
            for name in files:
                if name.startswith("."):
                    continue
                src = os.path.join(root, name)
                rel = os.path.relpath(src, ART)
                dst = os.path.join(BUILD_OUT, "art", rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copy2(src, dst)
                overlaid += 1

    game_json = os.path.join(BUILD_OUT, "game.json")
    with open(game_json) as fh:
        data = json.load(fh)
    render = data.setdefault("render", {})
    render.setdefault("mode", "legacy")
    render["scale"] = args.scale
    with open(game_json, "w") as fh:
        json.dump(data, fh, indent=1)

    print(f"open pack -> {os.path.relpath(BUILD_OUT, ROOT)} "
          f"({overlaid} original files overlaid, scale {args.scale})")
    print(f"run: cargo run -p openbounty-shell -- {os.path.relpath(game_json, ROOT)}")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command", required=True)

    p = sub.add_parser("checklist")
    p.set_defaults(func=cmd_checklist)

    p = sub.add_parser("verify")
    p.add_argument("--scale", type=int, default=1)
    p.add_argument("--similarity", type=float, default=6.0,
                   help="flag a near match at or below this average channel delta")
    p.add_argument("--verbose", action="store_true")
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser("build")
    p.add_argument("--scale", type=int, default=1)
    p.add_argument("--keep", action="store_true")
    p.set_defaults(func=cmd_build)

    args = ap.parse_args()
    sys.exit(args.func(args))


if __name__ == "__main__":
    main()
