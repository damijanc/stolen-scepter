CELL = 8
# Where a 5x7 shape sits in its 8x8 cell: one column in, top row clear.
OFFSET_X, OFFSET_Y = 1, 0


def lit(ch):
    """The (x, y) cell pixels `ch` lights; unknown characters are blank."""
    rows = GLYPHS.get(ch, GLYPHS[" "])
    return [(OFFSET_X + x, OFFSET_Y + y)
            for y, row in enumerate(rows)
            for x, c in enumerate(row) if c == "#"]


def text_width(text, scale=1):
    return len(text) * CELL * scale


def draw_text(canvas, text, x, y, color, scale=1, shadow=None):
    """Stamp `text` onto a `gen_objects.Canvas` at (x, y), `scale` px per dot."""
    dots = [(x + (i * CELL + gx) * scale, y + gy * scale)
            for i, ch in enumerate(text) for gx, gy in lit(ch)]
    if shadow is not None:
        for px, py in dots:
            canvas.rect(px + scale, py + scale, scale, scale, shadow)
    for px, py in dots:
        canvas.rect(px, py, scale, scale, color)
