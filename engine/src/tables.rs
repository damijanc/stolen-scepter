#[allow(clippy::too_many_arguments)]
const fn troop(
    index: i32,
    id: &'static str,
    skill_level: i32,
    hit_points: i32,
    move_rate: i32,
    melee_min: i32,
    melee_max: i32,
    ranged_min: i32,
    ranged_max: i32,
    ranged_ammo: i32,
    recruit_cost: i32,
    spoils_factor: i32,
    abilities: i32,
    morale_group: u8,
) -> TroopDef {
    TroopDef {
        index,
        id,
        skill_level,
        hit_points,
        move_rate,
        melee_min,
        melee_max,
        ranged_min,
        ranged_max,
        ranged_ammo,
        recruit_cost,
        spoils_factor,
        abilities,
        morale_group,
    }
}

pub fn troop_by_id(id: &str) -> Option<&'static TroopDef> {
    TROOPS.iter().find(|troop| troop.id == id)
}

pub fn troop_by_index(index: i32) -> Option<&'static TroopDef> {
    if index < 0 {
        return None;
    }

    TROOPS
        .get(index as usize)
        .filter(|troop| troop.index == index)
}
